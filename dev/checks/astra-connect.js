// Run with dev/astra-connect-smoke.js: isolated Electron app, deterministic app-server fixture.
const wait = ms => new Promise(r => setTimeout(r, ms));
const until = async fn => { for (let i = 0; i < 100; i++) { if (fn()) return; await wait(80); } throw new Error('UI condition timed out'); };
let checks = 0; const ok = (v, m) => { if (!v) throw new Error(m); checks++; };
await Lazy.load('astraconnect');
H.config.settings = { ...H.config.settings, enginePaths: { codex: '__ASTRA_FIXTURE__' } };
const a = H.agents().find(a => a.engine === 'codex' && !a.dock);
a.chatgptApps = true; a.effort = 'max'; a.verbosity = 'low'; a.autoMemory = false;
await saveConfig(); activate(a.id); await wait(200);
ok(document.querySelector('.ac-launch'), 'Astra tools launcher missing');
await AstraConnect.apps(a.id);
ok(document.querySelector('.ac-dialog:modal').textContent.includes('app-demo'), 'Installed app fallback name missing');
ok([...document.querySelectorAll('.ac-dialog:modal button')].find(b => b.textContent === 'Use in next message').disabled, 'Non-callable app was enabled');
document.querySelector('.ac-dialog:modal').close();
await Native.send(a.id, 'QUESTION');
await until(() => document.querySelector('.ac-question input'));
const chat = Native.chatOf(a.id); const card = document.querySelector('.ac-question');
ok(Native.isBusy(chat.id), 'Question terminated the turn');
ok(card.querySelector('input').getAttribute('aria-label') === 'Which color?', 'Accessible question label missing');
card.querySelector('input').value = 'Blue';
[...card.querySelectorAll('button')].find(b => b.textContent === 'Send answer').click();
await until(() => card.textContent.includes('Answer sent'));
ok(card.querySelector('input').disabled, 'Answered question remains editable');
await AstraConnect.steer(a.id, 'Please use blue');
await until(() => chat.messages.some(m => m.steered && m.text === 'Please use blue'));
ok(Native.isBusy(chat.id), 'Steering ended the turn');
await AstraConnect.connections(a.id);
ok(document.querySelector('.ac-dialog:modal').textContent.includes('Sign-in required'), 'Health status missing');
document.querySelector('.ac-dialog:modal').close();
Native.stop(a.id); await until(() => !Native.isBusy(chat.id));
await AstraConnect.models(a.id);
const dialog = document.querySelector('.ac-dialog:modal');
ok(dialog.querySelector('select').value === 'max', 'Maximum reasoning was lost');
[...dialog.querySelectorAll('button')].find(b => b.textContent === 'Apply to this chat').click();
await until(() => !document.querySelector('.ac-dialog:modal'));
ok(chat.model === 'test' && chat.effort === 'max', 'Model capabilities selection was not saved');
let rejected = false; try { await AstraConnect.steer(a.id, 'Late'); } catch { rejected = true; }
ok(rejected, 'Ended turn accepted a steer');
ok(!chat.messages.some(m => m.text === 'Blue'), 'Question answers persisted unexpectedly');
return { pass: true, checks };
