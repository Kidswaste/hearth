const wait = ms => new Promise(r => setTimeout(r, ms));
const until = async fn => { for (let i = 0; i < 100; i++) { if (fn()) return; await wait(100); } throw new Error('Timed out'); };
const assert = (v, s) => { if (!v) throw new Error(s); };
const a = H.agents().find(a => a.mode === 'native' && a.engine === 'codex');
assert(a, 'Codex agent exists');
H.config.settings = { ...H.config.settings, enginePaths: { codex: '__ASTRA_FIXTURE__' } };
a.model = 'test'; a.effort = 'high';
await saveConfig();
activate(a.id); await until(() => Native.hasView(a.id));
Native.newChat(a.id); await wait(300);
const view = Native.view(a.id), button = view.root.querySelector('.ms-btn');
assert(button.textContent.includes('High · Solo'), 'Shows default High');
button.click();
await until(() => document.querySelector('.ms-pop select:not(:disabled)'));
let select = document.querySelector('.ms-pop select');
assert([...select.options].map(o => o.value).join(',') === ',max', 'Uses actual model capabilities');
select.value = 'max'; select.dispatchEvent(new Event('change'));
assert(button.textContent.includes('Max · Solo'), 'Effort updates immediately');
assert(a.effort === 'high', 'Global default unchanged');
assert(Astra.reasoning(a.id).effort === 'max', 'Chat override applied');
select.value = ''; select.dispatchEvent(new Event('change'));
assert(Astra.reasoning(a.id).effort === 'high', 'Reset inherits High');
const split = [...document.querySelectorAll('.ms-pop .ms-pick')].find(b => b.textContent.includes('Split it up'));
split.click();
assert(Missions.current(a.id).id === 'split', 'Helpers armed');
assert(!Native.isBusy(Native.chatOf(a.id)?.id), 'Selection does not start a paid turn');
assert(!document.querySelector('.ms-pop'), 'Picker closes on mode selection');
assert(view.root.querySelectorAll('.ms-btn').length === 1, 'One control only');
Missions.set(a.id, 'normal');
Native.newChat(a.id); await wait(200);
assert(button.textContent.includes('High · Solo'), 'New chat reflects default');
activate(a.id); await wait(500);
assert(Native.view(a.id).root.isConnected, 'Live composer remains mounted');
Native.view(a.id).root.querySelector('.ms-btn').click();
return { ok: true, checks: 'Capabilities, chat effort, default reset, helper arming, no automatic send, single control' };
