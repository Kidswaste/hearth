// Sandboxed file:// frames cannot fetch sibling scripts on every Electron platform.
// Bundle only our fixed source and allow its exact hashes; no unsafe-inline/eval or network.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..', 'tools');
const read = name => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
const script = (read('creative-games.js') + '\n' + read('creative-preview.js')).replace(/<\/script/gi, '<\\/script');
const css = read('creative-preview.css');
const hash = text => crypto.createHash('sha256').update(text).digest('base64');
const html = `<!doctype html>
<!-- Generated by node dev/creative-preview-build.js; edit the source JS/CSS, then regenerate. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash(script)}'; style-src 'sha256-${hash(css)}'; connect-src 'none'">
<title>Creative preview</title><style>${css}</style></head><body>
<canvas width="640" height="360" tabindex="0" aria-label="Interactive creative preview"></canvas>
<nav><button id="start">Start</button><button id="reset">Reset</button><label><input id="sound" type="checkbox"> Game sounds</label></nav>
<p id="status" aria-live="polite">Loading preview…</p>
<div id="pad"><button data-dir="ArrowLeft" aria-label="Left">←</button><button data-dir="ArrowUp" aria-label="Up">↑</button><button data-dir="ArrowDown" aria-label="Down">↓</button><button data-dir="ArrowRight" aria-label="Right">→</button></div>
<script>${script}</script></body></html>\n`;
if (process.argv.includes('--check')) {
  if (read('creative-preview.html') !== html) throw Error('Creative preview is stale: node dev/creative-preview-build.js');
  console.log('creative preview: generated source and CSP hashes match');
} else { fs.writeFileSync(path.join(root, 'creative-preview.html'), html); console.log('creative preview built'); }
