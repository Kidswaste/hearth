const assert=require('node:assert/strict');
const C=require('../routines-core');
const mk=()=>C.normalize({agentId:'a',chatId:'c',how:{kind:'rounds',rounds:5},cap:5000});
const report=C.usageOf({input:4000,output:200,cached:3000,cacheWrite:250,reasoning:150,cost:.25});
assert.deepEqual(report,{input:4000,output:200,cached:3000,cacheWrite:250,fresh:750,tokens:4200,partial:false,cost:.25});
for(const u of [undefined,{}, {input:NaN,output:1},{input:1,output:-1},{input:'4',output:1}])assert.equal(C.usageOf(u),null);
assert.equal(C.usageOf({input:0,output:0}).tokens,0);
assert.equal(C.usageOf({input:10,output:5}).cost,null);
let r=mk();C.sent(r);C.roundEnded(r,{type:'done',text:'Changed the attack.',tokens:report.tokens,usage:report});
assert.equal(r.tokens,4200);assert.equal(r.usageTotals.cost,.25);assert.equal(r.usageTotals.cached,3000);
assert.equal(C.nextStep(r,{now:Date.now()+5000}).act,'stop');
assert.equal(C.nextStep(mk(),{lastTokens:6000}).act,'stop','first round uses previous reply as an estimate');
r=mk();C.sent(r);C.stop(r);C.roundEnded(r,{type:'done',tokens:4200,usage:report});
assert.equal(r.status,'stopped');assert.equal(r.tokens,4200,'stopping must not lose the final report');
r=mk();C.sent(r);C.pause(r);C.roundEnded(r,{type:'done',tokens:4200,usage:report});assert.equal(r.status,'paused');
r=mk();C.sent(r);let end=C.roundEnded(r,{type:'done',tokens:0,usage:null});
assert.equal(end.act,'pause');assert(r.usageUnknown);C.resume(r);assert.equal(C.nextStep(r).act,'pause');
r=mk();C.sent(r);C.roundEnded(r,{type:'error',tokens:4200,usage:report,text:'Failed after work'});assert.equal(r.tokens,4200);assert.equal(r.rounds[0].ok,false);
r=mk();C.sent(r);C.roundEnded(r,{type:'stopped',tokens:4200,usage:{...report,partial:true}});assert(r.usageUnknown);assert.equal(r.tokens,4200);
const restored=C.normalize(JSON.parse(JSON.stringify(r)));assert(restored.usageUnknown);assert.equal(restored.usageTotals.cached,3000);
r=mk();r.afterRestart=true;C.sent(r);C.restarted(r);assert.equal(r.status,'paused');assert(r.usageUnknown);
assert.equal(C.normalize({agentId:'a',chatId:'c',tokens:123}).tokens,123,'legacy totals remain unchanged');
r=mk();C.helperUsage(r,{input:300,output:50});assert.equal(r.tokens,350);assert.equal(r.usageTotals.output,50);C.helperUsage(r,null);assert(r.usageUnknown);
console.log('Routine accounting: cache/reasoning inclusion, missing vs zero, first-round forecast, errors, stop/pause, interrupted reload, legacy preservation passed');
