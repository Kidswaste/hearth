// options-data.js: a command's usage hint → the control the ⋯ Options panel shows.  node dev/options-test.js
const assert = require('assert');
const O = require('../options-data.js');
const k = (a) => O.control(a);
assert.deepStrictEqual(k(''), { kind: 'action' });
assert.strictEqual(k('[on | off]').kind, 'toggle');
assert.strictEqual(k('on|off').kind, 'toggle');
assert.deepStrictEqual(k('<low | medium | high | xhigh>').values, ['low', 'medium', 'high', 'xhigh']);
assert.deepStrictEqual(k('[today|week|month|all]').values, ['today', 'week', 'month', 'all']);
assert.deepStrictEqual(k('[off]').values, ['', 'off']);
assert.deepStrictEqual({ ...k('<0.1–8>'), step: 0 }, { kind: 'number', min: 0.1, max: 8, step: 0, unit: '', opt: false });
assert.strictEqual(k('<percent>').max, 100);
assert.strictEqual(k('[n]').kind, 'number');
assert.strictEqual(k('<message>').kind, 'text');
const m = k('[name | your own words | off]');
assert.strictEqual(m.kind, 'mixed'); assert.deepStrictEqual(m.values, ['off']);
assert.strictEqual(O.humanize('board-snap'), 'Board snap');
assert.strictEqual(O.tabOf('Three.js Lab'), 'lab');
assert.strictEqual(O.tabOf('Nothing known'), 'app');
assert.strictEqual(O.lineOf('density', 'compact'), '/density compact');
assert.strictEqual(O.lineOf('compact', ''), '/compact');
assert.ok(O.MODES.every((x) => x.lines.length && x.desc));
console.log('options-test: ok');
