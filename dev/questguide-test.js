const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const C = require('../questguide-core');
const M = require('../questguidemain');

(async () => {
  let now = 1800000000000;
  let s = C.start({ questId: 'song', title: 'A short song', kind: 'music', bpm: 126 }, now);
  assert.equal(C.current(s).check, 'app');
  assert.equal(C.observe(s, { running: false }, now), s);
  s = C.observe(s, { running: true }, now);
  assert.equal(C.current(s).check, 'bpm');
  assert.equal(C.observe(s, { telemetry: { at: now, bpm: 126 } }, now), s, 'one observation cannot finish multiple steps');
  now += 2000;
  assert.equal(C.observe(s, { telemetry: { at: now - 7000, bpm: 126 } }, now), s, 'stale tempo cannot pass');
  assert.equal(C.observe(s, { telemetry: { at: now, bpm: 120 } }, now), s);
  s = C.observe(s, { telemetry: { at: now, bpm: 126 } }, now);
  now += 2000;
  const t = { at: now, playing: true, bpm: 126, channels: [{ name: 'Bass', notes: 0, activity: 0.7 }] };
  assert.equal(C.observe(s, { telemetry: t }, now), s, 'naming a channel and auditioning without notes does not count');
  t.channels[0].notes = 4; t.channels[0].activity = 0;
  assert.equal(C.observe(s, { telemetry: t }, now), s, 'silent channel does not count');
  t.channels[0].activity = 0.3;
  s = C.observe(s, { telemetry: t }, now);
  assert.equal(C.current(s).id, 'shape');
  assert.throws(() => C.manual(s, 'bass', 'done', now), /step changed/);
  assert.throws(() => C.manual(s, 'shape', '', now), /short note/);
  s = C.manual(s, 'shape', 'Removed the kick for the second half', now);
  assert.equal(s.done.at(-1).kind, 'manual');

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hearth-guide-'));
  let running = false;
  const api = M.create({ dataDir: dir, localDir: dir, documentsDir: dir, now: () => now, pollRunning: async () => running });
  try {
    await api.call({ op: 'start', questId: 'fixture', kind: 'music', bpm: 130 });
    assert.equal(api.state().completed, 0);
    assert.equal(fs.existsSync(api.hardwareDir()), false, 'starting never silently installs an FL script');
    await api.call({ op: 'setup-fl' });
    assert.ok(fs.existsSync(path.join(api.hardwareDir(), 'device_HearthQuest.py')));
    running = true; now += 2000; await api.poll();
    assert.equal(api.state().step.id, 'tempo');
    now += 2000;
    const packet = { version: 1, at: now, bpm: 130, playing: false, channels: [], nonce: 'wrong-session' };
    fs.writeFileSync(api.telemetryFile, JSON.stringify(packet)); await api.poll();
    assert.equal(api.state().step.id, 'tempo', 'unpaired telemetry cannot advance');
    packet.nonce = api._nonce(); fs.writeFileSync(api.telemetryFile, JSON.stringify(packet)); await api.poll();
    assert.equal(api.state().step.id, 'bass');
    await api.call({ op: 'pause' });
    assert.equal(JSON.parse(fs.readFileSync(path.join(api.hardwareDir(), 'hearth-config.json'))).active, false);
    assert.throws(() => C.manual(api.state().session, 'bass', 'Made my bass', now), /Resume/);
    await api.call({ op: 'resume' });
    await api.call({ op: 'manual', stepId: 'bass', note: 'Piano-roll bass finished; grid observer cannot see this pattern' });
    await api.call({ op: 'back' });
    assert.equal(api.state().step.id, 'bass'); assert.equal(api.state().session.paused, true);
    api.dispose();
    const restart = M.create({ dataDir: dir, localDir: dir, documentsDir: dir, now: () => now, pollRunning: async () => false });
    assert.equal(restart.state().completed, 2, 'progress survives a process restart');
    assert.equal(restart.state().session.paused, true);
    await restart.call({ op: 'start', questId: 'outing:1', kind: 'custom', steps: [{ id: 'ready', title: 'Get ready', check: 'manual' }, { id: 'leave', title: 'Leave', check: 'manual' }], completedIds: ['ready'] });
    assert.equal(restart.state().step.id, 'leave');
    assert.equal(restart.state().session.done[0].source, 'outing-plan');
    await restart.call({ op: 'start', questId: 'visual:1', steps: [{ id: 'tool', title: 'Open the Lab', check: 'tool', action: { type: 'hearth-tool', tool: 'lab' } }] });
    await assert.rejects(() => restart.call({ op: 'tool-opened', stepId: 'tool', tool: 'forge' }), /does not match/);
    await restart.call({ op: 'tool-opened', stepId: 'tool', tool: 'lab' }); assert.equal(restart.state().completed, 1);
    restart.dispose();
  } finally { api.dispose(); }
  console.log(JSON.stringify({ pass: true, evidence: 'fresh matched FL observations, bass notes and activity, manual audit, pause/back, restart persistence, explicit setup and tool confirmation', fixture: dir }));
})().catch(err => { console.error(err); process.exitCode = 1; });
